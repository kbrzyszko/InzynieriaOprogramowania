pub fn camera(t: f32) -> Cam {
    if t >= 40.8 {
        return cam_at(t, CAM_C);
    }
    let mut c = cam_at(t, CAM_AB);
    // Follow the drill bit on its way down.
    let fd = window(t, 23.0, 23.6, 26.1, 26.6);
    if fd > 0.0 {
        c.y = lerp(c.y, wells::drill_depth(t) - 120.0, fd);
        c.z = lerp(c.z, 1.12, fd);
    }
    // Follow the water pushed up by the submersible pump.
    let fw = window(t, 36.6, 37.0, 39.3, 39.8);
    if fw > 0.0 {
        c.y = lerp(c.y, wells::push_front(t) + 150.0, fw);
        c.z = lerp(c.z, 1.5, fw);
    }
    c
}

pub fn world(s: &mut String, t: f32, cam: Cam) {
    let garden = 1.0 - smooth(prog(t, 41.0, 42.2));
    ground::background(s, garden, t);
    ground::lawn(s, cam);
    wells::lawn_props_a(s, t);
    ground::face(s);
    wells::act_a(s, t);
    wells::act_b(s, t);
    house::act_c(s, t);
    wells::shovel(s, t);
}
